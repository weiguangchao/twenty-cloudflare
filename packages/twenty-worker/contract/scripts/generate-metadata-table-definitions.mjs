// Generates src/workspace/metadata/constants/metadata-table-definitions.constant.ts
// from the old server's `core` schema: one meta_ table per metadata entity,
// same columns minus workspaceId, same foreign keys between those tables.
// Usage: node generate-metadata-table-definitions.mjs (needs the old Postgres)
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { Client } = require('pg');

const DATABASE_URL =
  process.env.PG_DATABASE_URL ??
  'postgres://postgres:postgres@localhost:5432/default';
const OUTPUT_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
  'src',
  'workspace',
  'metadata',
  'constants',
  'metadata-table-definitions.constant.ts',
);

// Parents before children, so seed rows can be inserted in this order.
const METADATA_TABLES = [
  'objectMetadata',
  'fieldMetadata',
  'indexMetadata',
  'indexFieldMetadata',
  'searchFieldMetadata',
  'view',
  'viewFieldGroup',
  'viewField',
  'viewFilterGroup',
  'viewFilter',
  'viewSort',
  'viewGroup',
  'pageLayout',
  'pageLayoutTab',
  'pageLayoutWidget',
  'navigationMenuItem',
  'commandMenuItem',
  'role',
  'roleTarget',
  'objectPermission',
  'fieldPermission',
  'permissionFlag',
  'rolePermissionFlag',
  'timelineActivityType',
  'relatedRecordPath',
  'featureFlag',
  'keyValuePair',
  'file',
];

const columnKind = ({ data_type: dataType, udt_name: udtName }) => {
  if (dataType === 'boolean') return 'boolean';
  if (dataType === 'jsonb' || dataType === 'json' || dataType === 'ARRAY') {
    return 'json';
  }
  if (udtName === 'int4' || udtName === 'int8') return 'integer';
  if (udtName === 'float8' || udtName === 'numeric') return 'real';
  return 'text';
};

const client = new Client({ connectionString: DATABASE_URL });

await client.connect();

const { rows: columns } = await client.query(
  `SELECT table_name, column_name, data_type, udt_name, is_nullable
     FROM information_schema.columns
    WHERE table_schema = 'core' AND table_name = ANY($1)
    ORDER BY table_name, ordinal_position`,
  [METADATA_TABLES],
);
const { rows: foreignKeys } = await client.query(
  `SELECT tc.table_name, kcu.column_name, ccu.table_name AS referenced_table, rc.delete_rule
     FROM information_schema.table_constraints tc
     JOIN information_schema.key_column_usage kcu
       ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
     JOIN information_schema.constraint_column_usage ccu
       ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
     JOIN information_schema.referential_constraints rc
       ON rc.constraint_name = tc.constraint_name AND rc.constraint_schema = tc.table_schema
    WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'core'
      AND tc.table_name = ANY($1) AND ccu.table_name = ANY($1)`,
  [METADATA_TABLES],
);

await client.end();

const definitions = METADATA_TABLES.map((entityName) => ({
  entityName,
  columns: columns
    .filter(
      (column) =>
        column.table_name === entityName &&
        column.column_name !== 'workspaceId',
    )
    .map((column) => {
      const foreignKey = foreignKeys.find(
        (key) =>
          key.table_name === entityName &&
          key.column_name === column.column_name,
      );

      return {
        name: column.column_name,
        kind: columnKind(column),
        isNullable: column.is_nullable === 'YES',
        ...(foreignKey
          ? {
              references: {
                entityName: foreignKey.referenced_table,
                onDelete: foreignKey.delete_rule.replace(' ', '_'),
              },
            }
          : {}),
      };
    }),
}));

const source = `// Generated by contract/scripts/generate-metadata-table-definitions.mjs from
// the old server's core schema. Do not edit by hand.
import { type MetadataTableDefinition } from '@/workspace/metadata/types/metadata-table-definition.type';

export const METADATA_TABLE_DEFINITIONS = ${JSON.stringify(definitions, null, 2)} as const satisfies readonly MetadataTableDefinition[];
`;

writeFileSync(OUTPUT_PATH, source);
console.log(`wrote ${definitions.length} table definitions`);
